MAIN_TEMPLATE = '''"""Entry point of the generated application.

Features are AUTO-DISCOVERED (plugin convention): drop a module under
`{package}/features/` exposing `register()` and it gets wired automatically.
Do NOT edit this file to wire a feature - parallel work items would collide
here (inter-stream merge conflicts). Only change it when the entry point
itself must evolve (e.g. starting a web server).

CLI contract (relied upon by the Autospec smoke run):

* ``main(argv=None)`` reads ``sys.argv[1:]`` when ``argv`` is None and returns
  the process exit code (0 when everything went fine).
* A hook whose signature accepts a positional parameter (or ``*args``) is
  called as ``register(argv)``; a hook taking no parameter is called as
  ``register()`` (backward compatible with every existing project).
* ``--help`` / ``-h`` prints the application name and the discovered feature
  modules. The same banner is printed when no argument was given and no hook
  consumes arguments, so a bare ``python main.py`` never stays silent.
* The hooks always run, ``--help`` included: a feature owning a real CLI parses
  the relayed argv itself (argparse prints its own help and raises SystemExit).
* A hook raising ``SystemExit`` (argparse) is left alone: it propagates.
* A hook returning a non-zero ``int`` sets the exit code (first one wins).

WEB PRODUCT (anything that must LISTEN on a port): the BARE entry point MUST
START THE SERVER. That is the smoke contract the factory checks, so a banner
followed by exit 0 is a FAILURE here; the banner below is only the default
behaviour of a product that has no server. Typically ``main()`` runs the feature
hooks first, then calls the package's ``create_app()`` and
``uvicorn.run(app, host="0.0.0.0", port=8000)``. ``--help`` must stay port-free.
"""

import inspect
import sys

from {package}.features import discover

APP_NAME = "{package}"
HELP_FLAGS = ("-h", "--help")


def _accepts_argv(hook) -> bool:
    """True when ``hook`` can be called as ``hook(argv)``."""
    try:
        params = inspect.signature(hook).parameters.values()
    except (TypeError, ValueError):  # builtins and other opaque callables
        return False
    for param in params:
        if param.kind in (
            inspect.Parameter.POSITIONAL_ONLY,
            inspect.Parameter.POSITIONAL_OR_KEYWORD,
            inspect.Parameter.VAR_POSITIONAL,
        ):
            return True
    return False


def _feature_names(hooks) -> list:
    """Module names (without the package prefix) behind the given hooks."""
    names = []
    for hook in hooks:
        module = getattr(hook, "__module__", "") or ""
        name = module.rsplit(".", 1)[-1] or "?"
        if name not in names:
            names.append(name)
    return names


def _print_usage(hooks) -> None:
    print(APP_NAME + " - application generated by Autospec")
    print("Usage: python main.py [--help] [feature arguments]")
    names = _feature_names(hooks)
    if names:
        print("Features ({{n}}):".format(n=len(names)))
        for name in names:
            print("  - " + name)


def main(argv: list | None = None) -> int:
    args = list(sys.argv[1:] if argv is None else argv)
    hooks = discover()
    if not hooks:
        print("Projet généré par Autospec — aucune fonctionnalité câblée pour l'instant.")
        return 0

    wants_help = any(arg in HELP_FLAGS for arg in args)
    consumers = [hook for hook in hooks if _accepts_argv(hook)]
    if wants_help or (not args and not consumers):
        _print_usage(hooks)

    status = 0
    for register in hooks:
        result = register(args) if _accepts_argv(register) else register()
        if isinstance(result, int) and not isinstance(result, bool) and result and not status:
            status = result
    return status


if __name__ == "__main__":
    raise SystemExit(main())
'''

