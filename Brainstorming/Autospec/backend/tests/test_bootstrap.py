@pytest.mark.parametrize("relative,backend,database", [
    (".autospec", "python", "sqlite"), (".venv", "python", "none"),
    ("node_modules", "node", "none"), ("target", "rust", "none"),
])
@pytest.mark.asyncio
async def test_external_runtime_directory_is_rejected_before_install(tmp_path, monkeypatch, relative, backend, database):
    project = state(backend=backend, database=database, framework="")
    scaffold(tmp_path, monkeypatch, project)
    assert bootstrap.prepare(project, tmp_path).ok
    outside = tmp_path.parent / (tmp_path.name + "-external")
