@pytest.mark.skipif(os.environ.get("AUTOSPEC_REAL_BOOTSTRAP") != "1", reason="Opt-in production bundle and Chromium validation")
@pytest.mark.asyncio
async def test_production_frontend_excludes_tests_and_detects_blank_page(tmp_path, monkeypatch):
    project = state(kind="frontend", frontend="react", database="none")
    scaffold(tmp_path, monkeypatch, project)
    assert bootstrap.prepare(project, tmp_path).ok
    features = tmp_path / "frontend/src/features"
    features.mkdir(exist_ok=True)
    feature = features / "Greeting.tsx"
    feature.write_text('export default function Greeting() { return <h1>Bonjour production</h1>; }\n')
    (features / "Greeting.test.tsx").write_text('import {it,expect} from "vitest"; it("unit", () => expect(true).toBe(true));\n')
    (features / "Greeting.spec.tsx").write_text('import {it,expect} from "vitest"; it("spec", () => expect(true).toBe(true));\n')
    result = await bootstrap.verify(project, tmp_path, timeout_s=180)
    assert result.ok, result.detail
    assert "Chromium" in result.detail

    app = tmp_path / "frontend/src/App.tsx"
