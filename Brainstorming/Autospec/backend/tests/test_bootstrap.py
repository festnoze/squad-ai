@pytest.mark.asyncio
async def test_http_chunked_response_is_decoded():
    async def handle(reader, writer):
        await reader.read(2048)
        writer.write(b'HTTP/1.1 200 OK\r\nTransfer-Encoding: chunked\r\nConnection: close\r\n\r\n8\r\n{"ok":tr\r\n3\r\nue}\r\n0\r\n\r\n')
        await writer.drain()
        writer.close()
    server = await asyncio.start_server(handle, "127.0.0.1", 0)
    try:
        status, body = await bootstrap._get(server.sockets[0].getsockname()[1], "/")
        assert status == 200 and json.loads(body) == {"ok": True}
    finally:
        server.close()
        await server.wait_closed()


