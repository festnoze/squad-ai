    unsafe_bundle = await bootstrap.verify_runtime(project, tmp_path, timeout_s=45)
    assert not unsafe_bundle.ok
    assert "Test-only module in production bundle" in unsafe_bundle.detail

    app.write_text(good_source)
    feature.write_text('export default function Greeting(): never { throw new Error("Production crash sentinel"); }\n')
    blank_page = await bootstrap.verify_runtime(project, tmp_path, timeout_s=45)
    assert not blank_page.ok and not blank_page.infra
