def test_a_help_that_exits_non_zero_fails(monkeypatch):
    """Exit 0 without argument is not enough: --help must work too."""
    monkeypatch.setattr(settings, "smoke_cli_help", True)
    _run_with_current_python(monkeypatch)
    state = _state("smoke-cli-broken-help")
    ws = _scaffold(workspace_dir(state.id), BROKEN_HELP_MAIN)
    pipeline = Pipeline(state, ScriptedRunner())

    ok, detail = pipeline._smoke_run_python(ws)

    assert ok is False
    assert "sort en erreur" in detail
    assert "unrecognized argument" in detail   # stderr is reported when stdout is empty


def test_stderr_noise_does_not_count_as_help(monkeypatch):
    """The launcher trap: `uv run` writes "Creating virtual environment..." on
    STDERR. Merging the two streams would make every mute CLI pass, so the probe
    captures them separately and only stdout satisfies the contract."""
    monkeypatch.setattr(settings, "smoke_cli_help", True)
    _run_with_current_python(monkeypatch)
    state = _state("smoke-cli-stderr")
    ws = _scaffold(workspace_dir(state.id), STDERR_ONLY_MAIN)
    pipeline = Pipeline(state, ScriptedRunner())

    ok, detail = pipeline._smoke_run_python(ws)

    assert ok is False
    assert "muet" in detail


def test_a_web_product_never_runs_the_help_probe(monkeypatch):
    """The probe belongs to the NON-web branch only: a web app is judged on its
    listening port, and `--help` on a server would hang or lie."""
    monkeypatch.setattr(settings, "smoke_cli_help", True)
    monkeypatch.setattr(settings, "smoke_run_timeout_s", 1.0)
    launched = _run_with_current_python(monkeypatch)

    class _DeadProc:
        pid = 4321
        returncode = 3
        stdout = None

        def poll(self):
            return self.returncode

    monkeypatch.setattr(subprocess, "Popen", lambda *a, **k: _DeadProc())
    monkeypatch.setattr(Pipeline, "_terminate_tree", staticmethod(lambda proc: None))
    monkeypatch.setattr(
        Pipeline, "_kill_workspace_port_holders", staticmethod(lambda port, ws: 0)
    )
    state = _state("smoke-cli-web")
    state.product_profile = "api"          # web by INTENT, no framework declared
    ws = _scaffold(workspace_dir(state.id), MUTE_MAIN)
    pipeline = Pipeline(state, ScriptedRunner())

    ok, detail = pipeline._smoke_run_python(ws)

    assert ok is False
    assert "ne démarre pas le serveur" in detail
    assert launched == []                  # nothing went through the CLI branch


def test_the_probe_relays_its_own_launcher(monkeypatch):
    """The probe reuses the resolved launcher argv and only APPENDS --help, so a
    project launched through `uv run` keeps being launched through it."""
    seen: list[list[str]] = []

    def runner(cmd, **kwargs):
        seen.append([str(c) for c in cmd])
        return subprocess.CompletedProcess(args=cmd, returncode=0, stdout="usage: x", stderr="")

    monkeypatch.setattr(subprocess, "run", runner)
    monkeypatch.setattr(settings, "smoke_cli_help", True)
    state = _state("smoke-cli-argv")
    ws = _scaffold(workspace_dir(state.id), MUTE_MAIN)
    pipeline = Pipeline(state, ScriptedRunner())

    ok, _detail = pipeline._smoke_run_python(ws)

    assert ok is True
    assert len(seen) == 2
    assert seen[1] == [*seen[0], "--help"]
    assert seen[0][-3:] == ["run", "python", "main.py"]


def test_the_helper_is_a_pure_probe_of_stdout(monkeypatch, tmp_path):
    """Unit view of the probe itself: exit code and stdout are the only inputs."""
    calls: list[dict] = []

    def runner(cmd, **kwargs):
        calls.append(kwargs)
        return subprocess.CompletedProcess(
            args=cmd, returncode=0, stdout="  usage: demo  ", stderr="noise"
        )

    monkeypatch.setattr(subprocess, "run", runner)
    ok, detail = Pipeline._smoke_cli_help_run(
        tmp_path, ["uv", "run", "python", "main.py"], dict(os.environ), 5.0
    )
    assert ok is True and "--help" in detail
    # stdout and stderr MUST be two distinct pipes (the launcher-noise trap):
    # capture_output gives exactly that, and stderr is never merged into stdout.
    assert calls[0]["capture_output"] is True
    assert calls[0].get("stderr") is not subprocess.STDOUT
