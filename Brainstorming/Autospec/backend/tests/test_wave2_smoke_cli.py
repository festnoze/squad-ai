"""FACTORY_IMPROVEMENTS #4 (smoke half): a NON-web product must ANSWER, not just
exit 0.

``exit 0`` is trivially satisfied by a ``main.py`` that prints nothing, so the
factory could ship a mute binary and call the smoke gate green. With
``SMOKE_CLI_HELP`` on, the gate additionally runs ``python main.py --help`` and
requires exit 0 AND a non-empty stdout (the CLI contract delivered by the
scaffold template).

These tests execute the scaffolded ``main.py`` FOR REAL, only swapping
``uv run python`` for the current interpreter: the contract under test is about
what the delivered entry point writes on stdout, not about uv. That is also what
makes the stderr trap observable - a launcher writing its own progress lines to
stderr must never make a mute CLI look talkative.
"""

import os
import subprocess
import sys
from pathlib import Path

import pytest

from autospec.agents.scripted import ScriptedRunner
from autospec.config import settings
from autospec.models import ProjectState, StoryStatus, UserStory
from autospec.orchestrator.pipeline import Pipeline
from autospec.storage import workspace_dir

_REAL_RUN = subprocess.run

MUTE_MAIN = "import sys\n\nraise SystemExit(0)\n"

HELPFUL_MAIN = (
    "import sys\n\n"
    "APP_NAME = 'demo'\n\n"
    "def main(argv=None):\n"
    "    argv = sys.argv[1:] if argv is None else list(argv)\n"
    "    print(APP_NAME + ' - application generated by Autospec')\n"
    "    print('Usage: python main.py [--help] [feature arguments]')\n"
    "    return 0\n\n"
    "raise SystemExit(main())\n"
)

# Exits 0 with no argument (the historic gate is happy) but blows up on --help.
BROKEN_HELP_MAIN = (
    "import sys\n\n"
    "if '--help' in sys.argv[1:]:\n"
    "    sys.stderr.write('unrecognized argument --help\\n')\n"
    "    raise SystemExit(2)\n"
    "raise SystemExit(0)\n"
)

# Writes ONLY on stderr: the launcher-noise trap. stdout stays empty, so the CLI
# is still mute as far as the contract is concerned.
STDERR_ONLY_MAIN = (
    "import sys\n\n"
    "sys.stderr.write('Creating virtual environment at: .venv\\n')\n"
    "raise SystemExit(0)\n"
)


def _state(project_id: str) -> ProjectState:
    st = ProjectState(id=project_id, name="app", goal="g")
    st.stories = [UserStory(id="US-1", epic_id="E", title="t", status=StoryStatus.DONE)]
    st.product_profile = "cli"
    return st


def _scaffold(ws: Path, main_py: str) -> Path:
    """A minimal NON-web python product: no web framework in its pyproject."""
    ws.mkdir(parents=True, exist_ok=True)
    (ws / "main.py").write_text(main_py, encoding="utf-8")
    (ws / "pyproject.toml").write_text(
        "[project]\nname='x'\ndependencies=[]\n", encoding="utf-8"
    )
    return ws


def _run_with_current_python(monkeypatch) -> list[list[str]]:
    """Replace ``uv run python main.py ...`` by ``<this python> main.py ...``.

    Returns the list of argv tails actually executed (``["main.py", ...]``), so a
    test can assert WHETHER the --help probe ran, not only what it concluded.
    Anything that is not a main.py launch (the workspace port killer, ...) is
    answered with a neutral success instead of being executed.
    """
    launched: list[list[str]] = []

    def runner(cmd, **kwargs):
        argv = [str(c) for c in cmd]
        if "main.py" not in argv:
            return subprocess.CompletedProcess(args=argv, returncode=0, stdout="", stderr="")
        tail = argv[argv.index("main.py"):]
        launched.append(tail)
        return _REAL_RUN([sys.executable, *tail], **kwargs)

    monkeypatch.setattr(subprocess, "run", runner)
    return launched


@pytest.fixture(autouse=True)
def _short_timeout(monkeypatch):
    monkeypatch.setattr(settings, "smoke_run_timeout_s", 30.0)


# ------------------------------------------------------------------ the gate

def test_a_mute_cli_fails_the_smoke_with_an_explicit_message(monkeypatch):
    monkeypatch.setattr(settings, "smoke_cli_help", True)
    launched = _run_with_current_python(monkeypatch)
    state = _state("smoke-cli-mute")
    ws = _scaffold(workspace_dir(state.id), MUTE_MAIN)
    pipeline = Pipeline(state, ScriptedRunner())

    ok, detail = pipeline._smoke_run_python(ws)

    assert ok is False
    # The message must name the defect AND the probe, so the fix loop knows what
    # to repair instead of hunting a mysterious "smoke failed".
    assert "muet" in detail
    assert "--help" in detail
    # The historic exit-0 run happened first, then the help probe.
    assert launched == [["main.py"], ["main.py", "--help"]]


def test_b_a_cli_that_documents_itself_passes(monkeypatch):
    monkeypatch.setattr(settings, "smoke_cli_help", True)
    launched = _run_with_current_python(monkeypatch)
