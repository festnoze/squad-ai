"""Wave 8: the smoke gate's CLI branch must never hang either.

Wave 7 fixed the product evaluator, which froze for 45 minutes on a delivered
app that kept a grandchild alive. The very same trap survived in the smoke gate:
``_smoke_run_python`` ran the CLI with ``subprocess.run(..., timeout=...)`` and
``_smoke_cli_help_run`` probed ``--help`` with ``capture_output=True,
timeout=...``. At the timeout ``subprocess.run`` kills only the DIRECT child
(``uv.exe``) and then calls ``communicate()`` to collect the output; on Windows
the grandchild survives with the INHERITED stdout pipe and that read blocks
forever. The gate's own message ("le CLI n'a pas terminé en Ns (boucle/serveur
bloquant ?)") claimed to cover exactly the case it could not survive.

These tests are deterministic and platform-neutral: they run the CURRENT
interpreter on a tiny ``main.py`` that spawns a real GRANDCHILD inheriting
stdout, and they check both halves of the contract - the gate returns fast, and
the grandchild is dead afterwards.
"""

import os
import subprocess
import sys
import time
from pathlib import Path

from autospec.agents.scripted import ScriptedRunner
from autospec.config import settings
from autospec.models import ProjectState, StoryStatus, UserStory
from autospec.orchestrator.pipeline import Pipeline
from autospec.storage import workspace_dir

# A CLI that spawns a grandchild (stdout INHERITED: it holds our pipe open) and
# then loops forever. This is the shape the gate's message already described.
LOOPING_MAIN = (
    "import pathlib, subprocess, sys, time\n"
    "child = subprocess.Popen([sys.executable, '-c', 'import time; time.sleep(60)'])\n"
    "pathlib.Path('grandchild.pid').write_text(str(child.pid), encoding='utf-8')\n"
    "print('working...', flush=True)\n"
    "while True:\n"
    "    time.sleep(1)\n"
)

# Exits 0 with no argument (the historic gate is happy) but --help spawns a
# grandchild and never returns: only the help probe can catch it.
HANGING_HELP_MAIN = (
    "import pathlib, subprocess, sys, time\n"
    "if '--help' in sys.argv[1:]:\n"
    "    child = subprocess.Popen([sys.executable, '-c', 'import time; time.sleep(60)'])\n"
    "    pathlib.Path('grandchild.pid').write_text(str(child.pid), encoding='utf-8')\n"
    "    print('usage: demo', flush=True)\n"
    "    time.sleep(60)\n"
    "raise SystemExit(0)\n"
)

# Exits immediately, but leaves a detached grandchild holding the stdout pipe:
# the read after the exit is the second half of the W7 trap.
EXIT_WITH_DETACHED_CHILD_MAIN = (
    "import pathlib, subprocess, sys\n"
    "child = subprocess.Popen([sys.executable, '-c', 'import time; time.sleep(60)'])\n"
    "pathlib.Path('grandchild.pid').write_text(str(child.pid), encoding='utf-8')\n"
    "print('bootstrap done', flush=True)\n"
    "raise SystemExit(0)\n"
)

# The nominal delivered CLI: exits 0 and documents itself on stdout.
HELPFUL_MAIN = (
    "import sys\n\n"
    "def main(argv=None):\n"
    "    print('demo - application generated by Autospec')\n"
    "    print('Usage: python main.py [--help] [feature arguments]')\n"
    "    return 0\n\n"
    "raise SystemExit(main())\n"
)


# ------------------------------------------------------------------ helpers

def _alive(pid: int) -> bool:
    """Is ``pid`` still running? ``os.kill(pid, 0)`` is NOT portable: on Windows
    os.kill TERMINATES the target whatever the signal, so we ask tasklist."""
    if os.name == "nt":
        out = subprocess.run(
            ["tasklist", "/FI", f"PID eq {int(pid)}", "/NH", "/FO", "CSV"],
            capture_output=True, text=True, timeout=30,
        ).stdout or ""
        return f'"{int(pid)}"' in out
    try:
        os.kill(pid, 0)
    except ProcessLookupError:
        return False
    except PermissionError:  # alive, owned by someone else
        return True
    return True


def _wait_dead(pid: int, timeout: float = 10.0) -> bool:
    deadline = time.monotonic() + timeout
    while time.monotonic() < deadline:
        if not _alive(pid):
            return True
        time.sleep(0.2)
    return not _alive(pid)


def _force_kill(pid: int) -> None:
    """Never leave a test process behind, whatever the assertions did."""
    try:
        if os.name == "nt":
            subprocess.run(
                ["taskkill", "/F", "/T", "/PID", str(int(pid))],
                stdout=subprocess.DEVNULL, stderr=subprocess.DEVNULL,
                check=False, timeout=30,
            )
        else:
            os.kill(pid, 9)
    except (OSError, subprocess.SubprocessError):
        pass


def _grandchild_pid(ws: Path, timeout: float = 10.0) -> int:
    deadline = time.monotonic() + timeout
    pid_file = ws / "grandchild.pid"
    while time.monotonic() < deadline:
        try:
            return int(pid_file.read_text(encoding="utf-8").strip())
        except (OSError, ValueError):
            time.sleep(0.1)
    raise AssertionError(f"main.py never wrote {pid_file}")


def _pipeline(monkeypatch, project_id: str, main_py: str, *,
              timeout: float = 3.0, cli_help: bool = True) -> tuple[Pipeline, Path]:
    """A NON-web python product whose entry point is ``main_py``, launched with
    THIS interpreter instead of ``uv run python`` (uv is not the contract here).
    """
    monkeypatch.setattr(settings, "smoke_run_timeout_s", timeout)
    monkeypatch.setattr(settings, "smoke_cli_help", cli_help)
    monkeypatch.setattr(
        Pipeline, "_resolve_cmd", staticmethod(lambda cmd: [sys.executable, "main.py"]),
    )
    state = ProjectState(id=project_id, name="app", goal="g")
    state.stories = [UserStory(id="US-1", epic_id="E", title="t", status=StoryStatus.DONE)]
    state.product_profile = "cli"
    ws = workspace_dir(state.id)
    ws.mkdir(parents=True, exist_ok=True)
    (ws / "main.py").write_text(main_py, encoding="utf-8")
    (ws / "pyproject.toml").write_text(
        "[project]\nname='x'\ndependencies=[]\n", encoding="utf-8"
    )
    return Pipeline(state, ScriptedRunner()), ws


def _record_events(monkeypatch, pipeline: Pipeline) -> list[tuple[str, dict]]:
    events: list[tuple[str, dict]] = []
    monkeypatch.setattr(
        pipeline.monitor, "event",
        lambda kind, **fields: events.append((kind, fields)),
    )
    return events


# -------------------------------------------------------------- the defect

def test_looping_cli_with_a_live_grandchild_is_tree_killed(monkeypatch):
    """The regression test: a CLI that loops with a live grandchild must not
    freeze the gate, and must leave NOTHING running behind."""
    pipeline, ws = _pipeline(monkeypatch, "w8-cli-loop", LOOPING_MAIN)
    events = _record_events(monkeypatch, pipeline)

    started = time.monotonic()
    ok, detail = pipeline._smoke_run_python(ws)
    elapsed = time.monotonic() - started

    assert elapsed < 20, f"the smoke gate hung for {elapsed:.1f}s"
    assert ok is False
    assert "n'a pas terminé" in detail and "boucle" in detail

    pid = _grandchild_pid(ws)
    try:
        assert _wait_dead(pid), f"grandchild {pid} survived the smoke timeout"
    finally:
        _force_kill(pid)

    assert events and events[0][0] == "smoke_cli"
    assert events[0][1] == {
        "probe": "run", "ok": False, "timed_out": True, "killed_tree": True,
    }


def test_help_probe_that_hangs_with_a_grandchild_is_tree_killed(monkeypatch):
    """Same trap one step further: ``main.py`` exits 0 (historic gate green) but
    ``--help`` hangs with a live grandchild. The probe must time out, tree-kill,
    and report - never block on the inherited pipe."""
    pipeline, ws = _pipeline(monkeypatch, "w8-cli-help-hang", HANGING_HELP_MAIN)
    events = _record_events(monkeypatch, pipeline)

    started = time.monotonic()
    ok, detail = pipeline._smoke_run_python(ws)
    elapsed = time.monotonic() - started

    assert elapsed < 20, f"the help probe hung for {elapsed:.1f}s"
    assert ok is False
    assert "`main.py --help` n'a pas terminé" in detail

    pid = _grandchild_pid(ws)
    try:
        assert _wait_dead(pid), f"grandchild {pid} survived the help timeout"
    finally:
        _force_kill(pid)

    # The exit-0 run passed, the help probe is the one that failed.
    assert [(kind, f["probe"], f["ok"]) for kind, f in events] == [
        ("smoke_cli", "run", True), ("smoke_cli", "help", False),
    ]
    assert events[1][1] == {
        "probe": "help", "ok": False, "timed_out": True, "killed_tree": True,
    }


def test_detached_grandchild_holding_the_pipe_does_not_block_the_gate(monkeypatch):
    """``main.py`` EXITS but its grandchild keeps the stdout pipe open: the old
    ``communicate()`` blocked there too. The gate must return on the exit code
    and stay bounded."""
    pipeline, ws = _pipeline(
        monkeypatch, "w8-cli-detached", EXIT_WITH_DETACHED_CHILD_MAIN,
        timeout=30.0, cli_help=False,
    )

    started = time.monotonic()
    ok, detail = pipeline._smoke_run_python(ws)
    elapsed = time.monotonic() - started

    pid = _grandchild_pid(ws)
    _force_kill(pid)

    assert elapsed < 20, f"the smoke gate hung for {elapsed:.1f}s"
    assert ok is True and detail == "CLI exécuté (code 0)"


# ------------------------------------------------------------ nominal paths

def test_a_documented_cli_still_passes(monkeypatch):
    """The nominal case is untouched: exit 0 plus a --help that writes on
    stdout is still the green path, and it reports both probes."""
    pipeline, ws = _pipeline(monkeypatch, "w8-cli-ok", HELPFUL_MAIN, timeout=30.0)
    events = _record_events(monkeypatch, pipeline)

    ok, detail = pipeline._smoke_run_python(ws)

    assert ok is True
    assert "--help" in detail and "documenté" in detail
    assert [(f["probe"], f["ok"], f["timed_out"]) for _kind, f in events] == [
        ("run", True, False), ("help", True, False),
    ]


def test_a_launch_that_cannot_start_is_reported_not_crashed(monkeypatch):
    """An unlaunchable command stays an infra message, not a traceback."""
    pipeline, ws = _pipeline(monkeypatch, "w8-cli-oserror", HELPFUL_MAIN)
    monkeypatch.setattr(
        Pipeline, "_resolve_cmd",
        staticmethod(lambda cmd: ["autospec-does-not-exist-w8", "main.py"]),
    )

    ok, detail = pipeline._smoke_run_python(ws)

    assert ok is False
    assert detail.startswith("lancement impossible")
